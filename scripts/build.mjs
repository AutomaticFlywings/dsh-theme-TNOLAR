import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
const manifest = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const html = readFileSync(resolve(root, 'assets/world-startup.html'), 'utf8');
const template = readFileSync(resolve(root, 'src/client.template.js'), 'utf8');
const theme = readFileSync(resolve(root, 'src/tnolar-theme.css'), 'utf8');

if (!template.includes('__STARTUP_HTML_JSON__') || !template.includes('__TNOLAR_THEME_CSS_JSON__')) {
  throw new Error('Missing client template placeholders');
}
if (!html.includes('<html')) throw new Error('Missing startup HTML');
if (manifest.dsh?.client?.platform !== 'web') throw new Error('Expected a DSH Web client plugin');

/**
 * DSH client module transport is a classic script, not a native ES module.
 * Its runtime registers a CJS-style factory with window.__ModuleLoader__.load().
 * Do not write top-level `export` or `import` to the packaged lib/client.js.
 * See packages/client/modules/src/client/system.ts in deepseek-harness.
 */
export function renderClientBundle() {
  const body = template
    .replace('__STARTUP_HTML_JSON__', JSON.stringify(html))
    .replace('__TNOLAR_THEME_CSS_JSON__', JSON.stringify(theme))
    .replace(/^export const name\s*=/m, 'const name =')
    .replace(/^export function apply\s*\(/m, 'function apply(');
  if (/^\s*(?:export|import)\b/m.test(body)) throw new Error('Client factory contains top-level ESM declarations');
  if (!body.includes("const name = 'dsh-theme-tnolar'")) throw new Error('Client plugin name not found');
  if (!body.includes('function apply(ctx)')) throw new Error('Client plugin apply() not found');
  return `// DSH classic client bundle (not ESM). Generated by scripts/build.mjs.\n`
    + `// Source: src/client.template.js, src/tnolar-theme.css, assets/world-startup.html\n`
    + `window.__ModuleLoader__.load({ id: ${JSON.stringify(manifest.name)}, factory: (require) => {\n`
    + `${body}\n`
    + `return { name, apply };\n`
    + `} });\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  mkdirSync(resolve(root, 'lib'), { recursive: true });
  const bundle = renderClientBundle();
  writeFileSync(resolve(root, 'lib/client.js'), bundle, 'utf8');
  console.log(`[${manifest.name}] wrote DSH classic-script client bundle (${bundle.length} characters)`);
}